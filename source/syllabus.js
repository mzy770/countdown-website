export const STUDY_CATEGORIES = [...new Set(STUDY_MODULES.map(t=>t.category))];
export function seedModules(state){
  if(state.syllabusVersion===SYLLABUS_VERSION)return state;
  const known=new Set([...state.tasks.map(t=>t.id),...(Array.isArray(state.completedModules)?state.completedModules:[])]);
  return {...state,tasks:[...state.tasks,...STUDY_MODULES.filter(t=>!known.has(t.id))],syllabusVersion:SYLLABUS_VERSION};
}
